-- Lưu tất cả file bằng Ctrl + s trong chế độ Normal
vim.keymap.set("n", "<C-S>", "<cmd>wa<cr>", { desc = "Save All Files" })
vim.keymap.set("i", "<C-S>", "<cmd>wa<cr>", { desc = "Save All Files" })
vim.keymap.set("n", "<C-s>", "<cmd>w<cr>", { desc = "Save Current File" })
vim.keymap.set("i", "<C-S>", "<cmd>wa<cr>", { desc = "Save All Files" })
